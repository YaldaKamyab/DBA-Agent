_ACTIONS = {POSTGRESQL: {"NO ACTION", "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT"},
            MYSQL: {"NO ACTION", "RESTRICT", "CASCADE", "SET NULL"},
            SQLITE: {"NO ACTION", "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT"},
            SQL_SERVER: {"NO ACTION", "CASCADE", "SET NULL", "SET DEFAULT", "RESTRICT"}}


def fk_action(action, dialect, where, notes):
    if action not in _ACTIONS[dialect]:
        raise SchemaGenerationError(f"{where}: {action} is not supported by {DIALECT_NAMES[dialect]} (InnoDB rejects "
                                    f"SET DEFAULT). Use another action with `revise`.")
    if dialect == SQL_SERVER and action == "RESTRICT":
        notes.append(f"{where}: SQL Server has no RESTRICT; NO ACTION (checked immediately) behaves the same.")
        return "NO ACTION"
    return action


# ------------------------------------------------------------------ helpers
def _clean(text):
    return re.sub(r"\s+", " ", str(text)).strip()


def _pk_name(t):
    return t["primary_key_name"] or f"pk_{t['name']}"


def _cols(t):
    return {c["name"]: c for c in t["columns"]}


def _check_key_columns(t, cols, dialect, where, base_of):
    """Types that cannot (or cannot reasonably) be part of a key in the dialect."""
    total = 0
    for c in cols:
        base, params = base_of[(t["name"], c)]
        if dialect == MYSQL:
            if base in _TEXTLIKE:
                raise SchemaGenerationError(f"{where}: MySQL cannot index {t['name']}.{c} ({base.upper()}) without a "
                                            f"key length; use VARCHAR(n) for indexed/key columns.")
            if base in ("varchar", "char") and params and params[0].isdigit():
                total += int(params[0]) * 4                          # utf8mb4 worst case
        if dialect == SQL_SERVER:
            raw = next(x["data_type"] for x in t["columns"] if x["name"] == c).lower()
            if base in ("text", "ntext", "image", "xml") or "(max)" in raw.replace(" ", ""):
                raise SchemaGenerationError(f"{where}: SQL Server cannot use {t['name']}.{c} ({raw.upper()}) in a key "
                                            f"or index; use VARCHAR(n)/NVARCHAR(n).")
    if dialect == MYSQL and total > 3072:
        raise SchemaGenerationError(f"{where}: key on ({', '.join(cols)}) can need up to {total} bytes (utf8mb4); "
                                    f"InnoDB allows 3072. Shorten the VARCHAR lengths.")


def _my_row_lower_bound(t, base_of):
    """Lower bound of the in-row bytes of a MySQL/MariaDB table under utf8mb4 (CHAR/VARCHAR/BINARY/VARBINARY only; every
    other column counts 0), so a result above 65,535 is a certain violation and never a false positive."""
    total = 0
    for c in t["columns"]:
        base, params = base_of[(t["name"], c["name"])]
        if not (params and params[0].isdigit()):
            continue
        n = int(params[0])
        if base in ("char", "varchar"):
            n *= 4
        if base in ("varchar", "varbinary"):
            n += 2 if (n > 255) else 1
        if base in ("char", "varchar", "binary", "varbinary"):
            total += n
    return total


def _order_tables(tables, dialect):
    """-> (ordered tables, deferred FKs [(table, fk)]). Self-references never count as dependencies."""
    names = [t["name"] for t in tables]
    tmap = {t["name"]: t for t in tables}
    deps = {n: {fk["ref_table"] for fk in tmap[n]["foreign_keys"] if fk["ref_table"] != n} for n in names}
    deferred, order, remaining = [], [], list(names)
    while remaining:
        ready = [n for n in remaining if not (deps[n] & set(remaining))]
        if ready:
            order.append(ready[0])
            remaining.remove(ready[0])
            continue
        # a cycle: close it with one foreign key, chosen deterministically (design order)
        cand = [(n, fk) for n in remaining for fk in tmap[n]["foreign_keys"]
                if fk["ref_table"] in remaining and fk["ref_table"] != n]
        broke = False
        for n, fk in cand:
            if _reaches(fk["ref_table"], n, deps, set(remaining)):
                if dialect == SQLITE:
                    order.append(remaining.pop(0))               # SQLite accepts forward references
                    broke = True
                    break
                deferred.append((n, fk))
                deps[n] = {f["ref_table"] for f in tmap[n]["foreign_keys"]
                           if f["ref_table"] != n and (n, f) not in deferred}
                broke = True
                break
        if not broke:
            raise SchemaGenerationError("Internal error: could not order tables for " + ", ".join(remaining))
    return [tmap[n] for n in order], deferred


def _reaches(src, dst, deps, alive):
    seen, stack = set(), [src]
    while stack:
        x = stack.pop()
        if x == dst:
            return True
        if x in seen:
            continue
        seen.add(x)
        stack += [y for y in deps.get(x, ()) if y in alive]
    return False


def _check_sqlserver_cascades(tables):
    """SQL Server rejects cycles and multiple cascade paths made of CASCADE / SET NULL / SET DEFAULT actions."""
    edges = {}
    for t in tables:
        for fk in t["foreign_keys"]:
            if "NO ACTION" == fk["on_delete"] == fk["on_update"] or {fk["on_delete"], fk["on_update"]} <= {"NO ACTION", "RESTRICT"}:
                continue
            if fk["ref_table"] == t["name"]:
                raise SchemaGenerationError(
                    f"SQL Server does not allow a self-referencing foreign key with ON DELETE/UPDATE "
                    f"{fk['on_delete']}/{fk['on_update']} ({fk['name']}). Use NO ACTION and handle it in application "
                    f"code or a trigger.")
            edges.setdefault(fk["ref_table"], []).append((t["name"], fk["name"]))

    def paths(root, node, path, count):
        for child, fkname in edges.get(node, ()):
            if child in path:
                raise SchemaGenerationError(f"SQL Server rejects cascading cycles ({' -> '.join(path + [child])} via {fkname}); "
                                            f"use NO ACTION on one of the foreign keys.")
            count[child] = count.get(child, 0) + 1
            paths(root, child, path + [child], count)
    for root in edges:
        count = {}
        paths(root, root, [root], count)
        multi = sorted(k for k, v in count.items() if v > 1)
        if multi:
            raise SchemaGenerationError(
                f"SQL Server rejects multiple cascade paths: deleting/updating `{root}` can reach "
                f"{', '.join('`' + m + '`' for m in multi)} by more than one cascading foreign key. Use NO ACTION on "
                f"one of them.")


def _check_names(tables, dialect):
    """Name collisions the DBMS would reject (per-table duplicates are already rejected by the design validator)."""
    seen = {}

    def claim(scope, name, what):
        k = (scope, name.lower())
        if k in seen:
            raise SchemaGenerationError(f"Name clash: {what} `{name}` is already used by {seen[k]} - names must be "
                                        f"unique within the {DIALECT_NAMES[dialect]} {scope or 'schema'}.")
        seen[k] = what
    for t in tables:
        if dialect in (POSTGRESQL, SQLITE):
            claim("relation", t["name"], f"table `{t['name']}`")
    for t in tables:
        pk = [(_pk_name(t), f"primary key of `{t['name']}`")] if t["primary_key"] else []
        uq = [(u["name"], f"unique constraint of `{t['name']}`") for u in t["unique_constraints"]]
        ix = [(i["name"], f"index of `{t['name']}`") for i in t["indexes"]]
        fk = [(f["name"], f"foreign key of `{t['name']}`") for f in t["foreign_keys"]]
        ck = [(c["name"], f"check of `{t['name']}`") for c in t["check_constraints"]]
        if dialect == POSTGRESQL:           # indexes (incl. PK/unique) share the relation namespace; constraints per table
            for n, w in pk + uq + ix:
                claim("relation", n, w)
        elif dialect == SQL_SERVER:         # every constraint name is schema-wide; index names are per table
            for n, w in pk + uq + fk + ck:
                claim("schema", n, w)
            for n, w in ix:
                claim("table:" + t["name"], n, w)
        elif dialect == MYSQL:              # FK and CHECK names schema-wide; index names per table
            for n, w in fk + ck:
                claim("schema", n, w)
            for n, w in pk[:0] + uq + ix:
                claim("table:" + t["name"], n, w)
        else:                               # SQLite: index names are global (and share the table namespace)
            for n, w in ix:
                claim("relation", n, w)
        for tr in t.get("triggers", []):    # generated trigger objects (one per operation for append_only)
            for n in (trigger_object_names(tr, t) if dialect == SQLITE else trigger_object_names(tr)):
                claim("trigger", n, f"trigger of `{t['name']}`")


# ------------------------------------------------------------------ structured triggers (SQLite only)
# Only SQLite triggers are generated: PostgreSQL / MySQL-MariaDB / SQL Server trigger code cannot be verified in this
# project (no server is available), so those DBMSs are refused with an instruction to enforce the rule in the
# application. Nothing below is reachable for another dialect.
_REPLACE_COVERS = "REPLACE"        # conflict replacement: INSERT OR REPLACE / REPLACE INTO / UPDATE OR REPLACE


def trigger_object_names(tr, t=None):
    """Names of the database objects one design trigger becomes. Pass the table `t` to include the conflict guards
    (generated for every SQLite table that has such a guard)."""
    if t is not None:
        return [o["name"] for o in _trigger_objects(SQLITE, t, tr)]
    if tr["kind"] == "append_only":
        return [f"{tr['name']}_{op.lower()}" for op in (tr.get("operations") or ["UPDATE", "DELETE"])]
    return [tr["name"]]


def _unique_keys(t):
    """Every key through which SQLite's REPLACE conflict resolution could delete an existing row:
    the implicit rowid, the primary key, UNIQUE constraints and unique indexes (partial ones with their condition)."""
    keys = [(None, [])]
    if t["primary_key"]:
        keys.append((list(t["primary_key"]), []))
    keys += [(list(u["columns"]), []) for u in t["unique_constraints"]]
    keys += [(list(i["columns"]), list(i.get("where") or [])) for i in t["indexes"] if i["unique"]]
    return keys


def _collision(dialect, t, extra=(), differing=None):
    """SQL condition (for a trigger WHEN) that is true when the row NEW collides on some unique key with an EXISTING row
    (`extra` further narrows the existing row, `differing` is a condition on the existing row). NULL key parts never
    collide (= is not true for NULL), exactly like UNIQUE."""
    q = lambda n: quote(dialect, n)
    nq = lambda n: "NEW." + q(n)
    terms = []
    for cols, where in _unique_keys(t):
        conds = ["rowid = NEW.rowid"] if cols is None else [f"{q(c)} = {nq(c)}" for c in cols]
        if where:
            conds.append(_where_sql(dialect, where, q))
        conds += list(extra) + ([differing] if differing else [])
        exists = f"EXISTS (SELECT 1 FROM {q(t['name'])} WHERE {' AND '.join(conds)})"
        terms.append(f"({_where_sql(dialect, where, nq)} AND {exists})" if where else exists)
    return "\n   OR ".join(terms)


def _trigger_objects(dialect, t, tr):
    """[{name, sql, covers}] - every trigger object one design trigger becomes (single source for the SQL and for the
    enforcement report). SQLite only."""
    where = f"{t['name']}: trigger {tr['name']}"
    if dialect != SQLITE:
        raise SchemaGenerationError(
            f"{where}: structured triggers are generated for SQLite only; {DIALECT_NAMES[dialect]} trigger syntax is not "
            f"implemented, so this rule would NOT be enforced. Remove the trigger and enforce the rule in the "
            f"application (rule mechanism 'application'), or write the trigger by hand outside schema.sql.")
    q = lambda n: quote(dialect, n)
    cols = {c["name"] for c in t["columns"]}
    tn = t["name"]
    out = []
    if tr["kind"] == "append_only":
        ops = tr.get("operations") or ["UPDATE", "DELETE"]
        for op in ops:
            verb = "updated" if op == "UPDATE" else "deleted"
            out.append({"name": f"{tr['name']}_{op.lower()}", "covers": [op], "sql":
                        f"CREATE TRIGGER {q(tr['name'] + '_' + op.lower())} BEFORE {op} ON {q(tn)}\nBEGIN\n"
                        f"    SELECT RAISE(ABORT, '{tn} is append-only: rows cannot be {verb}');\nEND;"})
        # REPLACE deletes the conflicting row WITHOUT firing DELETE triggers unless the connection has
        # recursive_triggers = ON (a per-connection setting). BEFORE INSERT / BEFORE UPDATE triggers always fire, so the
        # guards below make the protection independent of that setting.
        if "DELETE" in ops:
            out.append({"name": f"{tr['name']}_insert_conflict", "covers": [_REPLACE_COVERS], "sql":
                        f"CREATE TRIGGER {q(tr['name'] + '_insert_conflict')} BEFORE INSERT ON {q(tn)}\n"
                        f"WHEN {_collision(dialect, t)}\nBEGIN\n"
                        f"    SELECT RAISE(ABORT, '{tn} is append-only: a row with the same key already exists and cannot be "
                        f"replaced');\nEND;"})
            if "UPDATE" not in ops:
                out.append({"name": f"{tr['name']}_update_conflict", "covers": [_REPLACE_COVERS], "sql":
                            f"CREATE TRIGGER {q(tr['name'] + '_update_conflict')} BEFORE UPDATE ON {q(tn)}\n"
                            f"WHEN {_collision(dialect, t, extra=['rowid <> OLD.rowid'])}\nBEGIN\n"
                            f"    SELECT RAISE(ABORT, '{tn} is append-only: UPDATE would replace (delete) another row');\nEND;"})
        return out
    if tr["kind"] == "immutable_columns":
        bad = [c for c in tr["columns"] if c not in cols]
        if bad or not tr["columns"]:
            raise SchemaGenerationError(f"{where}: unknown or missing columns {bad or '(none)'}.")
        cond = " OR ".join(f"OLD.{q(c)} IS NOT NEW.{q(c)}" for c in tr["columns"])
        out.append({"name": tr["name"], "covers": ["UPDATE"], "sql":
                    f"CREATE TRIGGER {q(tr['name'])} BEFORE UPDATE OF {_qs(dialect, tr['columns'])} ON {q(tn)}\n"
                    f"WHEN {cond}\nBEGIN\n    SELECT RAISE(ABORT, '{tn}: {', '.join(tr['columns'])} cannot be "
                    f"changed after insert');\nEND;"})
        diff = "(" + " OR ".join(f"{q(c)} IS NOT NEW.{q(c)}" for c in tr["columns"]) + ")"
        out.append({"name": f"{tr['name']}_insert_conflict", "covers": [_REPLACE_COVERS], "sql":
                    f"CREATE TRIGGER {q(tr['name'] + '_insert_conflict')} BEFORE INSERT ON {q(tn)}\n"
                    f"WHEN {_collision(dialect, t, differing=diff)}\nBEGIN\n"
                    f"    SELECT RAISE(ABORT, '{tn}: {', '.join(tr['columns'])} cannot be changed after insert "
                    f"(replacing the row would change it)');\nEND;"})
        return out
    raise SchemaGenerationError(f"{where}: unknown trigger kind {tr['kind']!r}.")


def _trigger_sql(dialect, t, tr):
    return [o["sql"] for o in _trigger_objects(dialect, t, tr)]


# ------------------------------------------------------------------ what is really enforced
# Kinds that really restrict data when they exist. A non-unique index or a nullable column name proves nothing.
_ENFORCING = {"primary_key", "unique_constraint", "unique_index", "partial_unique_index", "check_constraint",
              "foreign_key", "trigger"}


def _catalog(dialect, tables):
    """Every constraint / index / trigger / column the generator emits for these tables, keyed by lower-case name.
    Trigger objects come from the same function that renders them; design-trigger names are aliases of their objects."""
    cat, alias, cols = {}, {}, {}

    def add(name, kind, table, **kw):
        cat[name.lower()] = dict(name=name, kind=kind, table=table, **kw)
    for t in tables:
        tn = t["name"]
        if t["primary_key"]:
            add(_pk_name(t), "primary_key", tn, columns=list(t["primary_key"]))
        for u in t["unique_constraints"]:
            add(u["name"], "unique_constraint", tn, columns=list(u["columns"]))
        for c in t["check_constraints"]:
            add(c["name"], "check_constraint", tn)
        for f in t["foreign_keys"]:
            add(f["name"], "foreign_key", tn, columns=list(f["columns"]))
        for i in t["indexes"]:
            kind = "index" if not i["unique"] else ("partial_unique_index" if i.get("where") else "unique_index")
            add(i["name"], kind, tn, columns=list(i["columns"]), where=dm.where_text(i.get("where")))
        for c in t["columns"]:
            cols[f"{tn}.{c['name']}".lower()] = {"name": f"{tn}.{c['name']}", "kind": "column", "table": tn,
                                                  "not_null": (not c["nullable"]) or c["name"] in t["primary_key"]}
        if dialect == SQLITE:
            for tr in t.get("triggers", []):
                objs = _trigger_objects(dialect, t, tr)
                for o in objs:
                    add(o["name"], "trigger", tn, covers=list(o["covers"]), trigger_kind=tr["kind"],
                        trigger_ops=list(tr.get("operations") or []), design_name=tr["name"])
                alias[tr["name"].lower()] = [o["name"].lower() for o in objs]
    return cat, alias, cols


def _emitted_names(statements, dialect):
    """Names that really appear after CONSTRAINT / INDEX / TRIGGER in the emitted statements (lower-case)."""
    o, c = {MYSQL: ("`", "`"), SQL_SERVER: ("[", "]")}.get(dialect, ('"', '"'))
    pat = re.compile(r"\b(?:CONSTRAINT|INDEX|TRIGGER)\s+" + re.escape(o) + r"((?:[^" + re.escape(c) + r"]|" + re.escape(c + c) +
                     r")+)" + re.escape(c))
    return {m.group(1).replace(c + c, c).lower() for m in pat.finditer(statements)}


def _caveats(dialect, obj):
    """Conditions under which a verified object does not (fully) protect - reported, never hidden."""
    k, out = obj["kind"], []
    if k == "foreign_key" and dialect == SQLITE:
        out.append(f"{obj['name']}: SQLite enforces foreign keys only on connections with PRAGMA foreign_keys = ON")
    if k == "check_constraint" and dialect == MYSQL:
        out.append(f"{obj['name']}: CHECK is enforced from MySQL 8.0.16 / MariaDB 10.2.1; older servers ignore it")
    if k == "partial_unique_index":
        out.append(f"{obj['name']}: unique only for rows where {obj['where']}")
    if k == "trigger":
        out.append(f"{obj['name']}: SQL-level protection only; anyone able to DROP TRIGGER / DROP TABLE / replace the "
                   f"database file can remove it")
        if obj["trigger_kind"] == "immutable_columns":
            out.append(f"{obj['name']}: DELETE followed by INSERT of the same key is permitted (rows are not protected "
                       f"from deletion); immutability holds for the life of a row only")
        if obj["trigger_kind"] == "append_only" and _REPLACE_COVERS in obj["covers"]:
            out.append(f"{obj['name']}: also rejects INSERT OR IGNORE / upsert of an existing key (raises instead)")
    return out


def rule_enforcement(design, tables, dialect=None, emitted=None):
    """Business rules split into three honest groups:
      database     - the rule's `implemented_by` objects were VERIFIED against what the generator really emitted
                     (constraint / unique index / trigger of the right table, or a NOT NULL column). The object's
                     existence and kind are verified; that it expresses the WHOLE rule is not, and is never inferred
                     from a name. `objects` and `caveats` say what exactly was matched and where protection is conditional.
      unverified   - declared as schema/trigger but the mapping is missing, unresolved, weak (non-unique index, nullable
                     column) or incomplete (append-only trigger that blocks only one operation). NOT counted as enforced.
      application  - still needs application logic (or declared as trigger but none was generated).
    `emitted` (set of names found in the generated SQL) lets generate_schema_sql confirm every object in the text."""
    dialect = dialect or design["dbms"]["id"]
    cat, alias, cols = _catalog(dialect, tables)
    if emitted is not None:
        cat = {k: v for k, v in cat.items() if k in emitted}
    db, unv, app = [], [], []

    def resolve(impl):
        objs, missing = [], []
        for i in impl:
            k = i.lower()
            if k in alias:
                found = [cat[n] for n in alias[k] if n in cat]
                (objs.extend(found) if len(found) == len(alias[k]) else missing.append(i))
            elif k in cat:
                objs.append(cat[k])
            elif k in cols:
                objs.append(cols[k])
            else:
                missing.append(i)
        return objs, missing

    for r in design.get("business_rules") or []:
        e = r.get("enforcement") or {}
        mech, impl = e.get("mechanism"), list(e.get("implemented_by") or [])
        if mech not in ("schema", "trigger"):
            app.append({"rule_id": r["id"], "declared": mech or "application", "reason": "application logic"})
            continue
        objs, missing = resolve(impl)
        triggers = [o for o in objs if o["kind"] == "trigger"]
        if mech == "trigger" and not triggers:
            app.append({"rule_id": r["id"], "declared": "trigger",
                        "reason": "declared as trigger, but no trigger was generated"})
            continue
        strong = [o for o in objs if o["kind"] in _ENFORCING or (o["kind"] == "column" and o["not_null"])]
        weak = [o for o in objs if o not in strong]
        problems = []
        if not impl:
            problems.append("no implemented_by objects are listed")
        if missing:
            problems.append("not found among the generated objects: " + ", ".join(missing))
        for o in weak:
            problems.append(f"{o['name']} is " + ("a non-unique index, which enforces nothing" if o["kind"] == "index" else
                            "a nullable column; a column name alone does not prove a constraint"))
        if impl and not strong and not problems:
            problems.append("no enforcing object")
        for dn in sorted({o["design_name"] for o in triggers if o["trigger_kind"] == "append_only"}):
            ops = next(o["trigger_ops"] for o in triggers if o["design_name"] == dn)      # operation coverage
            if not {"UPDATE", "DELETE"} <= set(ops):
                problems.append(f"append-only trigger {dn} blocks only {'/'.join(ops)} (the other operation stays allowed)")
        if problems:
            unv.append({"rule_id": r["id"], "mechanism": mech, "implemented_by": impl, "reason": "; ".join(problems)})
            continue
        caveats = []
        for o in strong:
            caveats += [c for c in _caveats(dialect, o) if c not in caveats]
        db.append({"rule_id": r["id"], "mechanism": mech, "implemented_by": [o["name"] for o in strong],
                   "objects": [{"name": o["name"], "kind": o["kind"], "table": o["table"]} for o in strong],
                   "verified": "objects exist in the generated SQL; semantic coverage of the rule is not checked",
                   "caveats": caveats})
    return {"database": db, "unverified": unv, "application": app}


def _enforcement_header(enf):
    def wrap(label, items):
        return [f"-- {l}" for l in textwrap.wrap(f"{label} " + (", ".join(items) or "none"), 112, subsequent_indent="   ")]
    lines = wrap("Business rules ENFORCED by this script (constraints / triggers):",
                 [f"{x['rule_id']}" for x in enf["database"]])
    lines.append("-- (Mapping verified against the generated objects; the script cannot prove an object expresses the whole rule.)")
    if enf.get("unverified"):
        lines += wrap("Business rules mapped to schema objects that could NOT be fully verified (not counted as enforced):",
                      [f"{x['rule_id']} ({x['reason']})" for x in enf["unverified"]])
    lines += wrap("Business rules NOT enforced by this script - application logic required:",
                  [f"{x['rule_id']} ({x['reason']})" if x["declared"] == "trigger" else x["rule_id"]
                   for x in enf["application"]])
    return lines


