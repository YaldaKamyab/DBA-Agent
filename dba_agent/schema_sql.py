DIALECT_NAMES = {POSTGRESQL: "PostgreSQL", MYSQL: "MySQL/MariaDB", SQLITE: "SQLite", SQL_SERVER: "SQL Server"}


class SchemaGenerationError(DBAAgentError):
    """The approved design cannot be translated to safe SQL for its DBMS (nothing was written)."""


# ------------------------------------------------------------------ quoting
def quote(dialect, name):
    if dialect == MYSQL:
        return "`" + name.replace("`", "``") + "`"
    if dialect == SQL_SERVER:
        return "[" + name.replace("]", "]]") + "]"
    return '"' + name.replace('"', '""') + '"'


def _qs(dialect, names):
    return ", ".join(quote(dialect, n) for n in names)


