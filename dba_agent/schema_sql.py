_RESERVED = {"order", "group", "user", "table", "index", "select", "from", "where", "key", "primary", "references",
             "check", "default", "constraint", "column", "values", "join", "limit", "offset", "desc", "asc", "insert",
             "update", "delete", "create", "drop", "alter", "grant", "union", "having", "case", "when", "end",
             "foreign", "unique", "null", "all", "and", "or", "not", "in", "is", "like", "between", "exists", "as",
             "by", "to", "on", "set", "add", "any", "current_date", "current_time", "current_timestamp",
             "current_user", "session_user", "system_user", "public", "type", "rank", "row", "rows", "range",
             "plan", "percent", "identity", "file", "backup", "authorization", "open", "close", "read", "rule"}
_LITERAL_OR_QUOTED = re.compile(r"""'(?:[^']|'')*'|"[^"]*"|`[^`]*`|\[[^\]]*\]""")
_FOREIGN = [
    (re.compile(r"::"), (MYSQL, SQLITE, SQL_SERVER), "PostgreSQL cast '::'"),
    (re.compile(r"\bilike\b", re.I), (MYSQL, SQLITE, SQL_SERVER), "ILIKE (PostgreSQL only)"),
    (re.compile(r"~"), (MYSQL, SQLITE, SQL_SERVER), "regex operator '~' (PostgreSQL only)"),
    (re.compile(r"\|\|"), (MYSQL, SQL_SERVER), "'||' (not string concatenation in this DBMS)"),
    (re.compile(r"\b(len|getdate|isnull|charindex|datediff|dateadd)\s*\(", re.I), (POSTGRESQL, MYSQL, SQLITE),
     "SQL Server function"),
    (re.compile(r"\b(length|now|ifnull|substr)\s*\(", re.I), (SQL_SERVER,), "function that does not exist in SQL Server"),
    (re.compile(r"\b(true|false)\b", re.I), (SQL_SERVER,), "TRUE/FALSE literal (SQL Server has none; use 1/0)"),
    (re.compile(r"\b(regexp|rlike)\b", re.I), (POSTGRESQL, SQLITE, SQL_SERVER), "REGEXP (MySQL only)"),
]


def _split_literals(expr):
    parts, pos = [], 0
    for m in _LITERAL_OR_QUOTED.finditer(expr):
        parts.append((False, expr[pos:m.start()]))
        parts.append((True, m.group(0)))
        pos = m.end()
    parts.append((False, expr[pos:]))
    return parts


# Words that may appear in a CHECK expression without being a column reference (operators, literals, CASE syntax,
# zero-argument functions). Function calls are recognised by a following '(' and are not looked up here.
_CHECK_WORDS = {"and", "or", "not", "in", "is", "null", "like", "glob", "between", "escape", "case", "when", "then", "else",
                "end", "true", "false", "unknown", "as", "cast", "regexp", "rlike", "ilike", "similar", "to", "distinct",
                "collate", "interval", "from", "for", "current_date", "current_time", "current_timestamp", "localtime",
                "localtimestamp", "binary", "div", "mod", "xor"}
_CHECK_TOKEN = re.compile(r"""'(?:[^']|'')*'|(?P<dq>"(?:[^"]|"")*")|(?P<bt>`(?:[^`]|``)*`)|(?P<br>\[(?:[^\]]|\]\])*\])"""
                          r"""|(?P<word>[A-Za-z_][\w$]*)|(?P<num>\d[\w.]*)|(?P<dot>\.)|(?P<other>\S)""")
_QUOTE_KINDS = {POSTGRESQL: ("dq",), MYSQL: ("bt",), SQLITE: ("dq", "bt", "br"), SQL_SERVER: ("br", "dq")}


_TIME_UNITS = {"microsecond", "second", "minute", "hour", "day", "week", "month", "quarter", "year", "frac_second",
               "sql_tsi_second", "sql_tsi_minute", "sql_tsi_hour", "sql_tsi_day", "sql_tsi_week", "sql_tsi_month",
               "sql_tsi_quarter", "sql_tsi_year"}


def check_unknown_columns(expr, columns, dialect, table=None):
    """Names in a CHECK expression that are neither a column of the table nor a function call / keyword / type name.
    This is a lexical scan (no parser): function calls (name followed by '(') and SQL keywords are skipped, the type
    after CAST(... AS) or '::' and the field name in EXTRACT(field FROM ...) are skipped, and a qualified `table.col`
    is checked as table + column. Quoted identifiers are checked for the quote styles the dialect uses for names."""
    known = {c.lower() for c in columns}
    toks = [(m.lastgroup, m.group(0), m.end()) for m in _CHECK_TOKEN.finditer(str(expr))]
    text, bad = str(expr), []
    skip_next = False
    for i, (kind, tok, end) in enumerate(toks):
        prev = toks[i - 1] if i else (None, "", 0)
        nxt = toks[i + 1] if i + 1 < len(toks) else (None, "", 0)
        if kind in ("dq", "bt", "br"):
            if kind not in _QUOTE_KINDS[dialect]:
                continue
            name = tok[1:-1].replace('""', '"').replace("``", "`").replace("]]", "]")
        elif kind == "word":
            name = tok
        else:
            continue
        if kind == "word":
            low = name.lower()
            if skip_next:
                skip_next = False
                continue
            if low in ("as", "collate") or prev[1] == "::" or (prev[1] == ":" and i >= 2 and toks[i - 2][1] == ":"):
                skip_next = low in ("as", "collate")
                if low == "as" and nxt[0] == "word":
                    continue
            if prev[1] == "::" or (prev[1] == ":" and i >= 2 and toks[i - 2][1] == ":"):
                continue
            if low in _CHECK_WORDS:
                continue
            if text[end:].lstrip().startswith("("):          # function call (or type with parameters)
                continue
            if prev[1] == "(" and i >= 2 and toks[i - 2][1].lower() == "extract":
                continue                                       # EXTRACT(year FROM col)
            if prev[1] == "(" and i >= 2 and toks[i - 2][1].lower() in ("timestampdiff", "timestampadd") \
                    and low in _TIME_UNITS:
                continue                                       # TIMESTAMPDIFF(DAY, a, b): the unit is not a column
            if low in _TIME_UNITS and i >= 2 and toks[i - 2][1].lower() == "interval":
                continue                                       # INTERVAL 1 DAY
        if prev[1] == ".":                                     # qualified reference: the column part of table.col
            qual = toks[i - 2][1] if i >= 2 else ""
            q = qual[1:-1] if qual[:1] in '"`[' else qual
            if table is not None and q.lower() != table.lower():
                bad.append(f"{qual}.{name}")
            elif name.lower() not in known:
                bad.append(name)
            continue
        if nxt[1] == "." and nxt[0] == "dot":
            continue                                           # qualifier part, validated with its column
        if name.lower() not in known and name not in bad:
            bad.append(name)
    return bad


_MY_NONDET_CALL = re.compile(
    r"\b(now|rand|uuid|uuid_short|curdate|curtime|sysdate|utc_date|utc_time|utc_timestamp|current_date|current_time|"
    r"current_timestamp|localtime|localtimestamp|user|current_user|session_user|system_user|database|schema|"
    r"connection_id|last_insert_id|row_count|found_rows|version|sleep|get_lock|release_lock|benchmark)\s*\(|"
    r"\bunix_timestamp\s*\(\s*\)", re.I)
_MY_NONDET_BARE = re.compile(r"\b(current_date|current_time|current_timestamp|localtime|localtimestamp|current_user|"
                             r"session_user|system_user)\b", re.I)


def _check_my_deterministic(code, where):
    m = _MY_NONDET_CALL.search(code) or _MY_NONDET_BARE.search(code)
    if m or "@" in code:
        what = (m.group(0).rstrip("( ").upper() if m else "user variable (@...)")
        raise SchemaGenerationError(
            f"{where}: CHECK uses {what}, which is nondeterministic/session-dependent and not allowed in MySQL/MariaDB CHECK "
            f"constraints (MySQL error 3814). Use a constant, or enforce this rule with a trigger or in the application.")


def check_column_refs(expr, columns):
    """Lower-cased names of the table's columns referenced by a CHECK expression (lexical scan, literals ignored)."""
    known, text, out = {c.lower() for c in columns}, str(expr), set()
    for m in _CHECK_TOKEN.finditer(text):
        k, tok = m.lastgroup, m.group(0)
        if k == "bt":
            name = tok[1:-1].replace("``", "`")
        elif k == "word" and not text[m.end():].lstrip().startswith("("):
            name = tok
        else:
            continue
        if name.lower() in known:
            out.add(name.lower())
    return out


def render_check(expr, columns, dialect, where, table=None):
    s = str(expr).strip()
    if not s:
        raise SchemaGenerationError(f"{where}: empty CHECK expression.")
    code = "".join(t for lit, t in _split_literals(s) if not lit)
    if ";" in code or "--" in code or "/*" in code or "*/" in code:
        raise SchemaGenerationError(f"{where}: CHECK expression must be a single expression (no ';' or comments).")
    if re.search(r"\bselect\b", code, re.I):
        raise SchemaGenerationError(f"{where}: subqueries are not allowed in CHECK constraints in any supported DBMS; "
                                    f"enforce this rule with a trigger or in the application.")
    if code.count("(") != code.count(")"):
        raise SchemaGenerationError(f"{where}: unbalanced parentheses in CHECK expression {s!r}.")
    if dialect == MYSQL:
        _check_my_deterministic(code, where)
    for rx, bad_in, what in _FOREIGN:
        if dialect in bad_in and rx.search(code):
            raise SchemaGenerationError(f"{where}: CHECK expression uses {what}, which is not valid in "
                                        f"{DIALECT_NAMES[dialect]}. Rewrite it with `revise`.")
    unknown = check_unknown_columns(s, columns, dialect, table)
    if unknown:
        raise SchemaGenerationError(f"{where}: CHECK expression references unknown column(s) "
                                    f"{', '.join('`' + u + '`' for u in unknown)}"
                                    f"{' of table `' + table + '`' if table else ''}. Fix the expression with `revise`.")
    cols = {c.lower() for c in columns if c.lower() in _RESERVED}
    if not cols:
        return s

    def fix(m):
        w = m.group(0)
        return quote(dialect, w) if w.lower() in cols else w
    return "".join(t if lit else re.sub(r"(?<![.\w])[A-Za-z_]\w*(?![\w(])", fix, t) for lit, t in _split_literals(s))


_NULL_TEST = re.compile(r"\bIS\s+(NOT\s+)?NULL\b", re.I)
_CONNECTIVE = re.compile(r"\b(AND|OR)\b", re.I)


def is_null_aware(expr):
    """True if a CHECK expression combines explicit NULL tests with AND/OR (a conditional rule such as
    "voided -> actor and reason present, otherwise both absent")."""
    code = "".join(t for lit, t in _split_literals(str(expr)) if not lit)
    return bool(_NULL_TEST.search(code) and _CONNECTIVE.search(code))


def nullable_columns_in_conditional_check(expr, nullable_columns):
    """Nullable columns used by a compound (AND/OR) CHECK that has NO explicit NULL test. SQL treats UNKNOWN as a pass, so
    `status <> 'cancelled' OR length(trim(notes)) > 0` accepts a cancelled row whose notes is NULL. The generated SQL is
    left unchanged (a plain CHECK on an optional column legitimately allows NULL); the weakness is reported instead."""
    code = "".join(t for lit, t in _split_literals(str(expr)) if not lit)
    if _NULL_TEST.search(code) or not _CONNECTIVE.search(code):
        return []
    words = set(re.findall(r"[A-Za-z_]\w*", code.lower()))
    return [c for c in nullable_columns if c.lower() in words]


def strict_check(expr_sql):
    """SQL treats an UNKNOWN (NULL) CHECK result as a PASS. For conditional rules that is wrong: with
    (status = 'voided' AND voided_by IS NOT NULL AND length(trim(voided_by)) > 0) OR (status <> 'voided' AND ...), a voided
    row with voided_by NULL gives TRUE AND NULL = NULL on one side and FALSE on the other, i.e. NULL -> accepted.
    CASE WHEN (...) THEN 1 ELSE 0 END = 1 turns UNKNOWN into a violation and is valid in all four DBMSs."""
    return f"CASE WHEN ({expr_sql}) THEN 1 ELSE 0 END = 1"


