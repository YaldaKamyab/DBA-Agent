class SchemaResult:
    def __init__(self, sql, dialect, table_order, deferred, notes, enforcement=None):
        self.sql, self.dialect, self.table_order, self.deferred_foreign_keys, self.notes = sql, dialect, table_order, deferred, notes
        self.enforcement = enforcement or {"database": [], "application": []}


def generate_schema_sql(design, fingerprint=None, validate=True):
    """Approved canonical design -> SchemaResult (.sql, .notes, .table_order, .deferred_foreign_keys).
    validate=False skips the whole-design validation (used only by unit tests with hand-built physical schemas)."""
    design = copy.deepcopy(design)
    if validate:
        try:
            design = dm.validate_design(design)
        except DBAAgentError as e:
            raise SchemaGenerationError(f"The design is not valid, so no SQL was generated: {e}")
    dialect = design["dbms"]["id"]
    if dialect not in DIALECTS:
        raise SchemaGenerationError(f"DBMS '{dialect}' is not supported by the SQL generator "
                                    f"(supported: {', '.join(DIALECTS)}).")
    q = lambda n: quote(dialect, n)
    tables = design["physical"]["tables"]
    if not tables:
        raise SchemaGenerationError("The design has no tables.")
    notes = []
    base_of = {}
    for t in tables:
        for c in t["columns"]:
            base_of[(t["name"], c["name"])] = check_type(c["data_type"], dialect, f"{t['name']}.{c['name']}")
    _check_names(tables, dialect)
    if dialect == SQL_SERVER:
        _check_sqlserver_cascades(tables)
    if dialect == MYSQL:
        for t in tables:
            size = _my_row_lower_bound(t, base_of)
            if size > 65535:
                raise SchemaGenerationError(
                    f"{t['name']}: row size too large for MySQL/MariaDB: its CHAR/VARCHAR/BINARY/VARBINARY columns need at least "
                    f"{size} bytes under utf8mb4 (4 bytes per character), but the limit is 65,535 bytes per row. Shorten "
                    f"the lengths or change large text columns to TEXT with `revise`.")
    ordered, deferred = _order_tables(tables, dialect)
    deferred_names = {(t, fk["name"]) for t, fk in deferred}
    tmap = {t["name"]: t for t in tables}

    # keys that a SQL Server FK may reference (filtered unique indexes cannot be referenced)
    def nullable_unique(t, cols):
        cm = _cols(t)
        return dialect == SQL_SERVER and any(cm[c]["nullable"] for c in cols)

    body, extra, strict, weak = [], [], [], []           # CREATE TABLE statements / statements after all tables / NULL-strict checks
    for t in ordered:
        name, cm = t["name"], _cols(t)
        pk = list(t["primary_key"])
        lines, inline_pk = [], False
        ident = [c for c in t["columns"] if c["identity"]]
        if len(ident) > 1:
            raise SchemaGenerationError(f"{name}: more than one identity column ({', '.join(c['name'] for c in ident)}).")
        for c in t["columns"]:
            where = f"{name}.{c['name']}"
            base, params = base_of[(name, c["name"])]
            parts = [q(c["name"]), " ".join(c["data_type"].split())]
            if c["identity"]:
                if c["default"] is not None:
                    raise SchemaGenerationError(f"{where}: an identity column cannot also have a DEFAULT.")
                if base not in _INT and base not in _SERIAL:
                    raise SchemaGenerationError(f"{where}: identity/auto-increment needs an integer type, not {c['data_type']}.")
                if dialect in (MYSQL, SQLITE) and pk != [c["name"]]:
                    raise SchemaGenerationError(f"{where}: in {DIALECT_NAMES[dialect]} an auto-increment column must be the "
                                                f"single-column primary key.")
                if dialect == SQLITE and c["data_type"].strip().upper() != "INTEGER":
                    raise SchemaGenerationError(f"{where}: SQLite auto-increment requires the exact type INTEGER "
                                                f"(got {c['data_type']}).")
                if dialect == POSTGRESQL and base not in _SERIAL:
                    parts.append("GENERATED BY DEFAULT AS IDENTITY")
                elif dialect == POSTGRESQL:
                    notes.append(f"{where}: {c['data_type']} already auto-generates values; no IDENTITY clause added.")
                if dialect == SQL_SERVER:
                    parts.append("IDENTITY(1,1)")
            elif base in _SERIAL and dialect != POSTGRESQL:
                raise SchemaGenerationError(f"{where}: {c['data_type']} is PostgreSQL-only.")
            parts.append("NOT NULL" if (not c["nullable"] or c["name"] in pk) else ("NULL" if dialect == SQL_SERVER else ""))
            if c["identity"] and dialect == MYSQL:
                parts.append("AUTO_INCREMENT")
            if c["identity"] and dialect == SQLITE:
                parts.append(f"CONSTRAINT {q(_pk_name(t))} PRIMARY KEY AUTOINCREMENT")
                inline_pk = True
            if c["default"] is not None:
                parts.append("DEFAULT " + render_default(c["default"], base, dialect, where))
            lines.append("    " + " ".join(p for p in parts if p))
        if pk and not inline_pk:
            _check_key_columns(t, pk, dialect, f"{name}: primary key", base_of)
            lines.append(f"    CONSTRAINT {q(_pk_name(t))} PRIMARY KEY ({_qs(dialect, pk)})")
        for u in t["unique_constraints"]:
            _check_key_columns(t, u["columns"], dialect, f"{name}: unique {u['name']}", base_of)
            if nullable_unique(t, u["columns"]):
                extra.append(_filtered_unique(dialect, t, u["name"], u["columns"], cm))
                notes.append(f"{name}.{u['name']}: SQL Server treats NULLs as equal in UNIQUE constraints, so a filtered "
                             f"unique index (WHERE ... IS NOT NULL) is used to match the other DBMSs.")
            else:
                lines.append(f"    CONSTRAINT {q(u['name'])} UNIQUE ({_qs(dialect, u['columns'])})")
        for ck in t["check_constraints"]:
            expr = render_check(ck["expression"], list(cm), dialect, f"{name}: check {ck['name']}", table=name)
            if dialect == MYSQL:
                _check_my_column_conflicts(t, ck, list(cm))
            if is_null_aware(ck["expression"]):
                expr = strict_check(expr)
                strict.append(f"{name}.{ck['name']}")
            else:
                loose = nullable_columns_in_conditional_check(
                    ck["expression"], [c["name"] for c in t["columns"] if c["nullable"] and c["name"] not in pk])
                if loose:
                    weak.append(f"{name}.{ck['name']} (nullable: {', '.join(loose)})")
            lines.append(f"    CONSTRAINT {q(ck['name'])} CHECK ({expr})")
        for fk in t["foreign_keys"]:
            if (name, fk["name"]) in deferred_names:
                continue
            lines.append("    " + _fk_sql(dialect, t, fk, tmap, base_of, notes, nullable_unique))
        end = ")"
        if dialect == MYSQL:
            end = ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
        body.append(f"CREATE TABLE {q(name)} (\n" + ",\n".join(lines) + f"\n{end};")
    alter = []
    for tname, fk in deferred:
        t = tmap[tname]
        alter.append(f"ALTER TABLE {q(tname)}\n    ADD " + _fk_sql(dialect, t, fk, tmap, base_of, notes, nullable_unique) + ";")
        notes.append(f"Circular dependency: foreign key `{fk['name']}` ({tname} -> {fk['ref_table']}) is added with ALTER TABLE "
                     f"after all tables exist. Loading data needs a NULL/deferred value on one side.")
    for t in ordered:
        for ix in t["indexes"]:
            _check_key_columns(t, ix["columns"], dialect, f"{t['name']}: index {ix['name']}", base_of)
            why = _missing_where(ix)
            if why:
                raise SchemaGenerationError(
                    f"{t['name']}: unique index {ix['name']} is {why} but has no structured 'where' condition, so it would be "
                    f"generated as an unconditional UNIQUE key and wrongly reject legitimate repeated rows. Add a 'where' "
                    f"list, e.g. [{{\"column\": \"status\", \"operator\": \"=\", \"value\": \"active\"}}], with `revise` - or, if "
                    f"the uniqueness really applies to ALL rows, set \"conditional\": false on the index.")
            if ix.get("where"):
                extra.append(_partial_index(dialect, t, ix))
                notes.append(f"{t['name']}.{ix['name']}: partial index, only rows where {dm.where_text(ix['where'])} are covered"
                             f"{' (so it is not a full unique key of the table)' if ix['unique'] else ''}.")
            elif ix["unique"] and nullable_unique(t, ix["columns"]):
                extra.append(_filtered_unique(dialect, t, ix["name"], ix["columns"], _cols(t)))
                notes.append(f"{t['name']}.{ix['name']}: unique index on nullable column(s) is filtered (WHERE ... IS NOT NULL) "
                             f"so that several NULLs are allowed, as in the other DBMSs.")
            else:
                extra.append(f"CREATE {'UNIQUE ' if ix['unique'] else ''}INDEX {q(ix['name'])} ON {q(t['name'])} "
                             f"({_qs(dialect, ix['columns'])});")
    pragma_recursive = False
    kinds = set()
    for t in ordered:
        for tr in t.get("triggers", []):
            extra += _trigger_sql(dialect, t, tr)
            kinds.add(tr["kind"])
            if tr["kind"] == "append_only" and "DELETE" in (tr.get("operations") or ["DELETE"]):
                pragma_recursive = True
            notes.append(f"{t['name']}.{tr['name']}: trigger ({tr['kind'].replace('_', ' ')}) is generated; it protects the "
                         f"table against changes made with SQL, not against someone dropping the trigger or replacing the "
                         f"database file.")
    if "append_only" in kinds:
        notes.append("Append-only protection does not depend on a connection setting: BEFORE INSERT/UPDATE guard triggers reject "
                     "INSERT OR REPLACE / REPLACE INTO / UPDATE OR REPLACE (and upserts or INSERT OR IGNORE) that would delete an "
                     "existing row through its rowid, primary key or a UNIQUE key. Not covered: DROP TRIGGER / DROP TABLE, "
                     "PRAGMA writable_schema, replacing the file. A table whose operations omit DELETE (or only UPDATE) "
                     "intentionally allows delete-and-reinsert.")
    if "immutable_columns" in kinds:
        notes.append("Immutable columns: UPDATE is blocked by trigger and INSERT OR REPLACE that would change them is rejected; "
                     "DELETE followed by INSERT of the same key is still allowed (combine with an append-only DELETE trigger "
                     "if rows must never disappear).")
    if pragma_recursive:
        notes.append("PRAGMA recursive_triggers = ON is kept as extra protection only (REPLACE then also fires DELETE triggers); "
                     "the guards above do not rely on it, so a connection that forgets it is still protected.")
    if strict:
        notes.append("CHECK constraints " + ", ".join(strict) + " test NULLs explicitly, so they are generated NULL-strict "
                     "(CASE WHEN ... THEN 1 ELSE 0 END = 1): an UNKNOWN result is a violation instead of a silent pass.")
    if weak:
        notes.append("CHECK constraints " + "; ".join(weak) + " combine conditions (AND/OR) over nullable columns without an "
                     "explicit IS [NOT] NULL test. SQL treats an UNKNOWN result as a PASS, so a NULL in those columns is "
                     "accepted by the CHECK. If the rule requires a value, make the column NOT NULL or add an explicit "
                     "IS NOT NULL test with `revise`; the rule is not reported as fully enforced for NULL values.")
    if dialect == MYSQL and any(t["check_constraints"] for t in tables):
        notes.append("CHECK constraints are enforced from MySQL 8.0.16 / MariaDB 10.2.1; older servers parse and ignore them.")
    if dialect == SQLITE:
        notes.append("SQLite enforces foreign keys only when PRAGMA foreign_keys = ON is set on each connection.")
    header = [f"-- schema.sql - {_clean(design['project_name'])} ({DIALECT_NAMES[dialect]})",
              "-- Generated deterministically by DBA Agent (Stage 6A) from the approved design; do not edit by hand.",
              f"-- Approved design fingerprint (SHA-256): {fingerprint or 'not recorded'}",
              f"-- Target: an EMPTY {DIALECT_NAMES[dialect]} database. Tables are created in foreign-key order."]
    header += [f"-- NOTE: {_clean(n)}" for n in notes]
    statements = "\n".join(body + alter + extra)
    enforcement = rule_enforcement(design, tables, dialect, _emitted_names(statements, dialect))
    header += _enforcement_header(enforcement)
    parts = ["\n".join(header)]
    if dialect == SQLITE:
        parts.append("PRAGMA foreign_keys = ON;" + ("\nPRAGMA recursive_triggers = ON;" if pragma_recursive else ""))
    parts += body + alter + extra
    return SchemaResult("\n\n".join(parts) + "\n", dialect, [t["name"] for t in ordered],
                        [{"table": t, "foreign_key": fk["name"]} for t, fk in deferred], notes, enforcement)


def _missing_where(ix):
    """Why a unique index without 'where' is suspected to be conditional (None = it is an ordinary unique index)."""
    if not ix["unique"] or ix.get("where"):
        return None
    flag = ix.get("conditional")
    if flag is True:
        return 'marked "conditional": true'
    if flag is False:
        return None
    if _PARTIAL_HINT.search(ix.get("purpose") or ""):
        return f"described as partial/conditional ({_clean(ix['purpose'])!r})"
    return None


def _where_sql(dialect, where, q):
    def lit(v):
        if isinstance(v, bool):
            return ("TRUE" if v else "FALSE") if dialect == POSTGRESQL else ("1" if v else "0")
        return "'" + v.replace("'", "''") + "'" if isinstance(v, str) else str(v)
    parts = []
    for c in where:
        col, op = q(c["column"]), c["operator"]
        if op == "IN":
            parts.append(f"{col} IN ({', '.join(lit(v) for v in c['value'])})")
        elif op in ("IS NULL", "IS NOT NULL"):
            parts.append(f"{col} {op}")
        else:
            parts.append(f"{col} {op} {lit(c['value'])}")
    return " AND ".join(parts)


def _partial_index(dialect, t, ix):
    """CREATE [UNIQUE] INDEX ... WHERE <structured condition>. SQL Server treats NULLs in a unique index as equal,
    so (as for ordinary nullable unique indexes) nullable columns not already tested get IS NOT NULL."""
    if dialect == MYSQL:
        raise SchemaGenerationError(f"{t['name']}: index {ix['name']} is partial, which MySQL/MariaDB does not support.")
    q = lambda n: quote(dialect, n)
    cm = _cols(t)
    cond = _where_sql(dialect, ix["where"], q)
    if ix["unique"] and dialect == SQL_SERVER:
        tested = {c["column"] for c in ix["where"]}
        cond = " AND ".join([cond] + [f"{q(c)} IS NOT NULL" for c in ix["columns"] if cm[c]["nullable"] and c not in tested])
    return (f"CREATE {'UNIQUE ' if ix['unique'] else ''}INDEX {q(ix['name'])} ON {q(t['name'])} "
            f"({_qs(dialect, ix['columns'])}) WHERE {cond};")


def _filtered_unique(dialect, t, name, cols, cm):
    q = lambda n: quote(dialect, n)
    where = " AND ".join(f"{q(c)} IS NOT NULL" for c in cols if cm[c]["nullable"])
    return f"CREATE UNIQUE INDEX {q(name)} ON {q(t['name'])} ({_qs(dialect, cols)}) WHERE {where};"


_MY_FK_BLOCKING = {"on_update": {"CASCADE", "SET NULL", "SET DEFAULT"}, "on_delete": {"SET NULL", "SET DEFAULT"}}


def _check_my_column_conflicts(t, ck, columns):
    """MySQL rejects a CHECK on an AUTO_INCREMENT column (error 3818) and on a column used in a foreign key with a
    value-changing referential action (error 3823). The engine id is shared by MySQL and MariaDB, so the stricter MySQL
    rule is applied to both; nothing is silently dropped - the design must be revised."""
    where = f"{t['name']}: check {ck['name']}"
    used = check_column_refs(ck["expression"], columns)
    for c in t["columns"]:
        if c["identity"] and c["name"].lower() in used:
            raise SchemaGenerationError(
                f"{where}: CHECK references AUTO_INCREMENT column `{c['name']}`, which MySQL does not allow (error 3818). "
                f"Remove the column from the CHECK or enforce the rule another way, with `revise`.")
    for fk in t["foreign_keys"]:
        for col in fk["columns"]:
            if col.lower() not in used:
                continue
            for key, label in (("on_update", "ON UPDATE"), ("on_delete", "ON DELETE")):
                if fk[key] in _MY_FK_BLOCKING[key]:
                    raise SchemaGenerationError(
                        f"{where}: CHECK references column `{col}`, which is used by foreign key `{fk['name']}` with "
                        f"{label} {fk[key]}; MySQL does not allow this combination (error 3823). Change the referential "
                        f"action to NO ACTION/RESTRICT or drop the column from the CHECK, with `revise`.")


def _fk_sql(dialect, t, fk, tmap, base_of, notes, nullable_unique):
    q = lambda n: quote(dialect, n)
    where = f"{t['name']}: foreign key {fk['name']}"
    cm, parent = _cols(t), tmap[fk["ref_table"]]
    for a in (fk["on_delete"], fk["on_update"]):
        if a == "SET NULL" and any(not cm[c]["nullable"] or c in t["primary_key"] for c in fk["columns"]):
            raise SchemaGenerationError(f"{where}: {a} needs every foreign-key column to be nullable "
                                        f"({', '.join(fk['columns'])}). Change the action or the column with `revise`.")
        if a == "SET DEFAULT" and any(cm[c]["default"] is None for c in fk["columns"]):
            raise SchemaGenerationError(f"{where}: SET DEFAULT needs a DEFAULT on every foreign-key column.")
    if dialect == SQL_SERVER:
        refset = set(fk["ref_columns"])
        keys = [set(parent["primary_key"])] + [set(u["columns"]) for u in parent["unique_constraints"]
                                              if not nullable_unique(parent, u["columns"])] + \
               [set(i["columns"]) for i in parent["indexes"] if i["unique"] and not i.get("where")
                and not nullable_unique(parent, i["columns"])]
        if refset not in keys:
            raise SchemaGenerationError(f"{where}: the referenced columns ({', '.join(fk['ref_columns'])}) are not a primary "
                                        f"key or full UNIQUE constraint of `{parent['name']}` in SQL Server (a filtered "
                                        f"unique index over nullable columns cannot be referenced).")
    od = fk_action(fk["on_delete"], dialect, where + " ON DELETE", notes)
    ou = fk_action(fk["on_update"], dialect, where + " ON UPDATE", notes)
    return (f"CONSTRAINT {q(fk['name'])} FOREIGN KEY ({_qs(dialect, fk['columns'])}) REFERENCES {q(fk['ref_table'])} "
            f"({_qs(dialect, fk['ref_columns'])}) ON DELETE {od} ON UPDATE {ou}")
