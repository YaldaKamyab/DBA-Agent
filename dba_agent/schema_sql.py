_INT = {"tinyint", "smallint", "mediumint", "int", "integer", "bigint", "int2", "int4", "int8"}
_SERIAL = {"serial", "bigserial", "smallserial", "serial2", "serial4", "serial8"}
_COMMON = {"decimal", "numeric", "real", "float", "char", "varchar", "text", "date", "time", "timestamp", "binary",
           "varbinary"}
_BASES = {
    POSTGRESQL: _INT - {"tinyint", "mediumint"} | _SERIAL | _COMMON - {"binary", "varbinary"} | {
        "double precision", "float4", "float8", "boolean", "bool", "character", "character varying", "bytea",
        "timestamptz", "timetz", "time without time zone", "time with time zone", "timestamp without time zone",
        "timestamp with time zone", "interval", "uuid", "json", "jsonb"},
    MYSQL: _INT | _COMMON | {"double", "double precision", "boolean", "bool", "tinytext", "mediumtext", "longtext",
                             "tinyblob", "blob", "mediumblob", "longblob", "datetime", "year", "json", "enum", "set",
                             "bit"},
    SQLITE: None,                      # SQLite accepts any type name; only the syntax is checked
    SQL_SERVER: (_INT - {"mediumint", "int2", "int4", "int8"}) | _COMMON - {"text", "timestamp"} | {
        "bit", "money", "smallmoney", "nchar", "nvarchar", "text", "ntext", "image", "datetime", "datetime2",
        "smalldatetime", "datetimeoffset", "uniqueidentifier", "xml"},
}
_TYPE_RE = re.compile(r"^[A-Za-z][A-Za-z0-9 ]*?\s*(\((?P<p>[^()]*)\))?(\s+unsigned)?$", re.I)
_PARAM_RE = re.compile(r"^\s*(\d+|max)(\s*,\s*\d+)?\s*$", re.I)
_ENUM_RE = re.compile(r"^\s*'(?:[^']|'')*'(\s*,\s*'(?:[^']|'')*')*\s*$")
# Legacy safety net for designs WITHOUT the structured index flag "conditional": only declarative phrases such as
# "partial unique index" / "unique only when ..." count. A bare "WHERE" in prose (e.g. "used in queries WHERE status is
# active") describes queries, not uniqueness, and is NOT treated as proof. Structured flag wins: "conditional": false
# means unconditional, "conditional": true without a "where" is refused.
_PARTIAL_HINT = re.compile(
    r"\b(partial|conditional|filtered)\s+(unique\s+)?(index|key|constraint|uniqueness)\b"
    r"|\bunique\s+(only\s+)?(among|for|within)\s+(the\s+)?(rows|records)\s+(where|with|that)\b"
    r"|\bunique\s+(only\s+)?(when|if|while)\b", re.I)
_TEXTLIKE = {"text", "tinytext", "mediumtext", "longtext", "blob", "tinyblob", "mediumblob", "longblob", "json",
             "ntext", "image", "xml", "bytea", "clob"}


_LEN = {"char", "varchar", "character", "character varying", "binary", "varbinary", "nchar", "nvarchar"}
_PREC = {"decimal", "numeric"}
_TEMPORAL = {"time", "timestamp", "timetz", "timestamptz", "datetime", "datetime2", "datetimeoffset", "interval",
             "time without time zone", "time with time zone", "timestamp without time zone",
             "timestamp with time zone"}
# (min, max) character/byte length per dialect and base type
_LEN_RANGE = {
    POSTGRESQL: {"*": (1, 10485760)},
    MYSQL: {"char": (0, 255), "binary": (0, 255), "varchar": (0, 16383), "varbinary": (0, 65535)},   # varchar: utf8mb4 = 4 bytes/char
    SQL_SERVER: {"char": (1, 8000), "varchar": (1, 8000), "binary": (1, 8000), "varbinary": (1, 8000),
                 "nchar": (1, 4000), "nvarchar": (1, 4000)},
}
_PREC_MAX = {POSTGRESQL: (1000, 1000), MYSQL: (65, 30), SQL_SERVER: (38, 38)}
_TIME_FSP = {POSTGRESQL: 6, MYSQL: 6, SQL_SERVER: 7}


def _check_params(base, nums, dialect, where, data_type):
    """Validate numeric type parameters (count and range) for one dialect. nums = list of ints (or 'max')."""
    if dialect == SQLITE or not nums:
        return
    bad = lambda why: SchemaGenerationError(f"{where}: invalid type {data_type!r}: {why}.")
    n = len(nums)
    if base in _LEN:
        if base == "binary" and dialect == POSTGRESQL:
            return
        if n != 1:
            raise bad("expects exactly one length parameter")
        if nums[0] == "max":
            return
        lo, hi = _LEN_RANGE[dialect].get(base, _LEN_RANGE[dialect].get("*", (1, 1)))
        if not lo <= nums[0] <= hi:
            extra = " characters (tables are created as utf8mb4: 4 bytes per character within the 65,535-byte row limit)" \
                if dialect == MYSQL and base == "varchar" else ""
            raise bad(f"length must be between {lo} and {hi}{extra}")
    elif base in _PREC:
        if n > 2:
            raise bad("expects (precision[, scale])")
        pmax, smax = _PREC_MAX[dialect]
        if not 1 <= nums[0] <= pmax:
            raise bad(f"precision must be between 1 and {pmax}")
        sc = nums[1] if n == 2 else 0
        top = smax if dialect == POSTGRESQL else min(nums[0], smax)     # PostgreSQL allows scale > precision
        if not 0 <= sc <= top:
            raise bad(f"scale must be between 0 and {top}")
    elif base in _TEMPORAL:
        if n != 1 or not 0 <= nums[0] <= _TIME_FSP[dialect]:
            raise bad(f"expects one fractional-seconds precision between 0 and {_TIME_FSP[dialect]}")
        if dialect == SQL_SERVER and base not in ("time", "datetime2", "datetimeoffset"):
            raise bad("does not take parameters")
    elif base in ("float", "double precision", "double") and (dialect != MYSQL or base == "float") or base == "bit":
        if base == "bit":
            ok = dialect == MYSQL and n == 1 and 1 <= nums[0] <= 64
        elif dialect == MYSQL:
            ok = (n == 1 and 0 <= nums[0] <= 53) or (n == 2 and nums[0] <= 255 and nums[1] <= min(30, nums[0]))
        else:
            ok = n == 1 and 1 <= nums[0] <= 53 and base == "float"
        if not ok:
            raise bad("parameters out of range")
    elif dialect == MYSQL and base in _INT:
        if n != 1 or not 1 <= nums[0] <= 255:
            raise bad("display width must be a single number between 1 and 255")
    elif dialect == MYSQL and base in ("double", "double precision"):
        if n != 2 or nums[0] > 255 or nums[1] > min(30, nums[0]):
            raise bad("expects (M,D)")
    elif dialect == MYSQL and base in ("text", "blob", "year"):
        if n != 1 or nums[0] > 65535:
            raise bad("parameter out of range")
    elif dialect == MYSQL and base in ("enum", "set"):
        return
    else:
        raise bad(f"{base} does not take parameters")


_MY_NEEDS_PARAM = {"varchar", "varbinary", "enum", "set"}


def check_type(data_type, dialect, where):
    s = " ".join(str(data_type).split())
    m = _TYPE_RE.match(s)
    if not m:
        raise SchemaGenerationError(f"{where}: data type {data_type!r} is not a plain type name with optional "
                                    f"(length) - cannot generate it safely.")
    base, params, flags = parse_type(s)
    p = m.group("p")
    if dialect == MYSQL and base in _MY_NEEDS_PARAM and (p is None or not p.strip()):
        raise SchemaGenerationError(f"{where}: invalid type {data_type!r}: MySQL/MariaDB {base.upper()} requires "
                                    f"{'a length, e.g. ' + base.upper() + '(255)' if base in ('varchar', 'varbinary') else 'a value list, e.g. ' + base.upper() + chr(40) + chr(39) + 'a' + chr(39) + ',' + chr(39) + 'b' + chr(39) + chr(41)}.")
    if p is not None:
        ok = _ENUM_RE.match(p) if (dialect == MYSQL and base in ("enum", "set")) else _PARAM_RE.match(p)
        if not ok:
            raise SchemaGenerationError(f"{where}: type parameters in {data_type!r} are not supported.")
        if "max" in p.lower() and not (dialect == SQL_SERVER and base in ("varchar", "nvarchar", "varbinary")):
            raise SchemaGenerationError(f"{where}: (MAX) is only valid for SQL Server varchar/nvarchar/varbinary.")
    if p is not None and not (dialect == MYSQL and base in ("enum", "set")):
        nums = ["max" if x.strip().lower() == "max" else int(x) for x in p.split(",")]
        _check_params(base, nums, dialect, where, data_type)
    if "unsigned" in flags and dialect != MYSQL:
        raise SchemaGenerationError(f"{where}: UNSIGNED is MySQL/MariaDB-only ({DIALECT_NAMES[dialect]} design).")
    allowed = _BASES[dialect]
    if allowed is not None and base not in allowed:
        raise SchemaGenerationError(f"{where}: type {data_type!r} is not a known {DIALECT_NAMES[dialect]} type "
                                    f"(wrong dialect?). Fix the column type with `revise`.")
    return base, params


# ------------------------------------------------------------------ defaults
_NUM = re.compile(r"^[+-]?\d+(\.\d+)?$")
_STR = re.compile(r"^'(?:[^']|'')*'$")
_KIND = {"current_timestamp": "ts", "current_timestamp()": "ts", "now()": "ts", "getdate()": "ts",
         "sysdatetime()": "ts", "localtimestamp": "ts", "current_date": "date", "curdate()": "date",
         "current_date()": "date", "current_time": "time", "curtime()": "time", "current_time()": "time",
         "gen_random_uuid()": "uuid", "uuid()": "uuid", "newid()": "uuid"}
_NOW = {POSTGRESQL: {"ts": "CURRENT_TIMESTAMP", "date": "CURRENT_DATE", "time": "CURRENT_TIME",
                     "uuid": "gen_random_uuid()"},
        MYSQL: {"ts": "CURRENT_TIMESTAMP", "date": "(CURRENT_DATE)", "time": "(CURRENT_TIME)", "uuid": "(UUID())"},
        SQLITE: {"ts": "CURRENT_TIMESTAMP", "date": "CURRENT_DATE", "time": "CURRENT_TIME", "uuid": None},
        SQL_SERVER: {"ts": "CURRENT_TIMESTAMP", "date": "(CAST(GETDATE() AS DATE))",
                     "time": "(CAST(GETDATE() AS TIME))", "uuid": "NEWID()"}}


def render_default(raw, base, dialect, where):
    s = str(raw).strip()
    low = s.lower()
    if not s:
        raise SchemaGenerationError(f"{where}: empty DEFAULT.")
    if low == "null":
        out = "NULL"
    elif _NUM.match(s):
        out = s
        if dialect == POSTGRESQL and base in ("boolean", "bool"):
            if s not in ("0", "1"):
                raise SchemaGenerationError(f"{where}: boolean DEFAULT {s} is not 0/1.")
            out = "TRUE" if s == "1" else "FALSE"
    elif _STR.match(s):
        out = s
    elif low in ("true", "false"):
        out = low.upper() if dialect in (POSTGRESQL, MYSQL) else ("1" if low == "true" else "0")
    elif low in _KIND:
        out = _NOW[dialect][_KIND[low]]
        if out is None:
            raise SchemaGenerationError(f"{where}: DEFAULT {s} (UUID generation) has no SQLite equivalent; "
                                        f"remove the default or supply the value in the application.")
    else:
        raise SchemaGenerationError(
            f"{where}: DEFAULT {s!r} cannot be translated safely. Supported: numbers, 'text' literals, TRUE/FALSE, NULL, "
            f"CURRENT_TIMESTAMP/NOW(), CURRENT_DATE, CURRENT_TIME, UUID generation.")
    if dialect == MYSQL and base in _TEXTLIKE and not out.startswith("("):
        out = f"({out})"                                  # MySQL: BLOB/TEXT/JSON defaults must be expressions
    if dialect == SQL_SERVER and not (out.startswith("(") or _NUM.match(out) or _STR.match(out) or out in ("NULL", "CURRENT_TIMESTAMP")):
        out = f"({out})"
    return out


