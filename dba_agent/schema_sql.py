"""Stage 6A - deterministic schema.sql generator.

generate_schema_sql(design, fingerprint) turns the *physical* part of an approved canonical design (design.json) into
CREATE TABLE / ALTER TABLE / CREATE INDEX statements for one of the four supported DBMS families. No LLM is involved
and nothing is guessed: whatever cannot be translated safely raises SchemaGenerationError with an actionable message
(fix the design with `revise`). The same design always gives byte-identical SQL.

Dialect decisions (see README "Stage 6A"):
  * Every identifier is quoted ("x" PostgreSQL/SQLite, `x` MySQL/MariaDB, [x] SQL Server), so reserved words are safe.
  * Identity columns: PostgreSQL GENERATED BY DEFAULT AS IDENTITY (BY DEFAULT so seed.sql may insert explicit ids),
    MySQL AUTO_INCREMENT, SQLite INTEGER PRIMARY KEY AUTOINCREMENT, SQL Server IDENTITY(1,1).
  * Tables are created in foreign-key dependency order. A real cycle between tables is broken by emitting the
    closing foreign key(s) as ALTER TABLE ... ADD CONSTRAINT after all CREATE TABLEs (not possible in SQLite, which
    accepts forward references inside CREATE TABLE).
  * Indexes are separate CREATE INDEX statements after the tables.

Rule enforcement is reported honestly: SchemaResult.enforcement and the schema.sql header separate business rules that
this script really enforces (constraints, partial unique indexes, generated triggers) from rules that still need
application logic - a rule declared "trigger" is only listed as enforced if a structured trigger was generated for it.
Structured triggers (design `triggers`: append_only, immutable_columns) are generated for SQLite only; every other DBMS
raises SchemaGenerationError instead of emitting SQL that was never checked. CHECK expressions that test NULLs
explicitly are generated NULL-strict (see strict_check).

HONEST SCOPE: the checks here are static. The generator knows each dialect's documented rules (types, defaults,
FK actions, key-size limits, cascade paths ...) but only SQLite output is executed in this project's tests; the other
dialects are NOT verified against a real server. CHECK expressions are copied from the design after a lexical sanity
check (no subqueries, no statement separators, no obviously foreign-dialect syntax) - they are not parsed.
"""
